// Харьцангуй зам — `@/` alias нь шалгалтын скриптийн орчинд
// задардаггүй (compile хийсэн CJS дээр alias үлддэггүй).
import { API_BASE } from "./config";

export function photoUrl(photo: { url: string }): string {
  // Хуучин backend бүтэн хаяг буцаадаг. Frontend ба backend тус тусдаа
  // шинэчлэгддэг тул хоёр хэлбэрийг ХОЁУЛАНГ нь зөв боловсруулна — эс бөгөөс
  // шинэчлэлтийн хооронд `/api/cpms` + `http://…` гэж наалдаж эвдэрнэ.
  if (/^https?:\/\//i.test(photo.url)) return photo.url;

  return `${API_BASE}${photo.url.startsWith("/") ? "" : "/"}${photo.url}`;
}

import assert from "node:assert/strict";
import { handleMock } from "../lib/mock/handler";
import { getDb, MOCK_IDS } from "../lib/mock/store";
import { executionState, matchDependencyLocations, orderWorkDependencies, type WorkExecutionPlan } from "../lib/work-execution";

const call = (method: string, path: string, payload?: unknown) => handleMock(method, path.split("/"), "", payload);
call("POST", "auth/login", { email: "admin@cpms.test" });
const db = getDb();
const response = call("POST", `projects/${MOCK_IDS.projectId}/blocks`, { name: "Хамаарлын тест", floors: 2, unitsPerFloor: 1, startDate: "2026-11-18" });
assert.equal(response.status, 201);
const blockId = (response.body as { data: { id: string } }).data.id;
const types = db.workTypes.filter((type) => type.level === "floor").slice(0, 3);
assert.equal(types.length, 3);
const floors = db.locations.filter((location) => location.blockId === blockId && location.level === "floor").slice(0, 2);
assert.equal(call("POST", `blocks/${blockId}/work-items`, { workTypeIds: types.map((type) => type.id), locationIds: floors.map((floor) => floor.id), plannedQty: 10 }).status, 201);
const works = db.workItems.filter((work) => work.blockId === blockId);
const find = (type: number, floor: number) => works.find((work) => work.workTypeId === types[type].id && work.locationId === floors[floor].id)!;
const a = find(0, 0); const b = find(1, 0); const c = find(2, 0);
const url = `blocks/${blockId}/execution-plan`;
const read = () => (call("GET", url).body as { data: WorkExecutionPlan }).data;
const initial = read();
assert.deepEqual(initial.predecessors, {});
assert.deepEqual(initial.order.map((id) => db.byId.get(id)!.workTypeId), [types[0].id, types[0].id, types[1].id, types[1].id, types[2].id, types[2].id]);
const before = works.map((work) => ({ id: work.id, qty: work.plannedQty, price: work.budgetUnitPrice, start: work.plannedStartDate, end: work.plannedEndDate, accepted: work.acceptedQty }));
const mapping = matchDependencyLocations(b, [a.id], [b.id, find(1, 1).id], works, db.locations);
assert.equal(mapping.missing.length, 0);
assert.deepEqual(mapping.links[1].predecessorIds, [find(0, 1).id], "Repeated links match the correct floor");
const save = call("POST", `${url}/dependencies`, { version: initial.version, links: [...mapping.links, { workItemId: c.id, predecessorIds: [a.id] }] });
assert.equal(save.status, 200);
const current = read();
assert.ok(current.order.indexOf(a.id) < current.order.indexOf(b.id));
assert.equal(call("POST", `${url}/dependencies`, { version: initial.version, links: [{ workItemId: c.id, predecessorIds: [] }] }).status, 409);
assert.equal(call("POST", `${url}/dependencies`, { version: current.version, links: [{ workItemId: a.id, predecessorIds: [b.id] }] }).status, 422);
assert.equal(read().version, current.version, "Rejected cycles preserve all links and order");
assert.equal(call("POST", `${url}/move`, { version: current.version, workItemId: b.id, relativeToId: a.id, position: "before" }).status, 422);
assert.equal(call("POST", `${url}/move`, { version: current.version, workItemId: c.id, relativeToId: b.id, position: "before" }).status, 200);
assert.deepEqual(works.map((work) => ({ id: work.id, qty: work.plannedQty, price: work.budgetUnitPrice, start: work.plannedStartDate, end: work.plannedEndDate, accepted: work.acceptedQty })), before);
assert.equal(executionState(b, [a]), "Өмнөх ажил хүлээж буй");
assert.equal(executionState(b, [{ ...a, actualEndDate: "2026-11-18" }]), "Өмнөх ажлууд дууссан");
assert.equal(executionState({ ...b, reportedQty: 1 }, [a]), "Хийгдэж байна");
assert.equal(orderWorkDependencies(["a", "b"], { a: ["b"], b: ["a"] }), null);
assert.deepEqual(orderWorkDependencies(["d", "b", "c", "a"], { b: ["a"], c: ["a"], d: ["b", "c"] }), ["a", "b", "c", "d"]);
const incomplete = works.filter((work) => work.id !== find(0, 1).id);
assert.ok(matchDependencyLocations(b, [a.id], [find(1, 1).id], incomplete, db.locations).missing.length, "Missing floor prerequisites are explicit");
const foreign = db.workItems.find((work) => work.blockId !== blockId)!;
assert.equal(call("POST", `${url}/dependencies`, { version: read().version, links: [{ workItemId: b.id, predecessorIds: [foreign.id] }] }).status, 422);
call("POST", "auth/login", { email: "site_engineer@cpms.test" });
assert.equal(call("POST", `${url}/dependencies`, { version: read().version, links: [{ workItemId: b.id, predecessorIds: [] }] }).status, 403);
console.log("PASS: selection order, floor mapping, fork/join relations, cycles, stale edits, scope and unchanged quantities/dates.");

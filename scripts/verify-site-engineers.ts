import assert from "node:assert/strict";
import { handleMock } from "../lib/mock/handler";
import { getDb, MOCK_IDS } from "../lib/mock/store";
import type { ListEnvelope, SiteEngineerAssignmentSummary, WorkItem } from "../lib/api/types";

const db = getDb();
const call = (method: string, path: string, body?: unknown, query = "") => handleMock(method, path.split("/"), query, body);
const admin = () => call("POST", "auth/login", { email: "admin@cpms.test", password: "x" });
const project = `projects/${MOCK_IDS.projectId}/queue`;
const path = `blocks/${MOCK_IDS.blockId}/site-engineer-assignments`;
const summary = () => (call("GET", path).body as { data: SiteEngineerAssignmentSummary }).data;
const queue = () => (call("GET", project, undefined, "?type=check&pageSize=200").body as ListEnvelope<WorkItem>);
admin();
const makeEngineer = (email: string) => {
  const res = call("POST", "users", { name: email, email, role: "site_engineer", password: "password", scopeBlockIds: [MOCK_IDS.blockId] });
  assert.equal(res.status, 201);
  return (res.body as { data: { id: string } }).data;
};
const a = makeEngineer("site-assigned-a@cpms.test"), b = makeEngineer("site-assigned-b@cpms.test");
const groups = summary().groups.filter((g) => g.pendingCheck > 0);
assert.ok(groups.length >= 2);
const [first, second] = groups;
const assign = (groupId: string, id: string | null) => call("POST", path, { workTypeGroupId: groupId, siteEngineerId: id });
assert.equal(assign(first.groupId, a.id).status, 200);
assert.equal(assign(second.groupId, b.id).status, 200);
call("POST", "auth/login", { email: "site-assigned-a@cpms.test" });
const mine = queue();
assert.equal(mine.meta.total, first.pendingCheck);
assert.equal((call("GET", `${project}/counts`).body as { data: { check: number } }).data.check, mine.meta.total);
assert.equal(assign(first.groupId, b.id).status, 403);
const foreign = db.workItems.find((w) => w.blockId === MOCK_IDS.blockId && db.workTypes.find((t) => t.id === w.workTypeId)?.groupId === second.groupId && w.reviewState === "pending_check")!;
assert.equal(call("POST", `work-items/${foreign.id}/inspections`, { stage: "site_check", result: "accepted", acceptedQty: 1 }).status, 403);
assert.equal((call("GET", `work-items/${foreign.id}`).body as { data: WorkItem }).data.canCheckThisWorkItem, false);
const own = mine.data[0];
assert.equal((call("GET", `work-items/${own.id}`).body as { data: WorkItem }).data.canCheckThisWorkItem, true);
const added: WorkItem = { ...own, id: "new-assigned-work", name: "Шинээр нэмсэн ажил", reviewState: "pending_check" };
db.workItems.push(added); db.byId.set(added.id, added);
assert.equal(queue().meta.total, first.pendingCheck + 1);
admin();
assert.equal(assign(first.groupId, b.id).status, 200);
call("POST", "auth/login", { email: "site-assigned-a@cpms.test" });
assert.equal(queue().meta.total, 0);
call("POST", "auth/login", { email: "site-assigned-b@cpms.test" });
assert.equal(queue().meta.total, first.pendingCheck + second.pendingCheck + 1);
admin();
assert.equal(assign(first.groupId, null).status, 200);
assert.equal(summary().groups.find((g) => g.groupId === first.groupId)?.needsAssignment, true);
const admins = call("GET", "users").body as { data: { id: string; role: string }[] };
assert.equal(assign(first.groupId, admins.data.find((u) => u.role === "admin")!.id).status, 422);
call("POST", "auth/login", { email: "site-assigned-b@cpms.test" });
assert.equal(call("POST", `work-items/${own.id}/inspections`, { stage: "site_check", result: "accepted", acceptedQty: 1 }).status, 403);
console.log("PASS: site-engineer assignment, candidates, own queue/counts, foreign check denial, inherited new work, reassignment, removal, and role validation.");
